//! Poseidon permutation over the f128 base field used by the STARK examples.
//!
//! Parameters: width 3, x^5 S-box, 8 full rounds and 57 partial rounds. The
//! round constants are produced with the reference Grain LFSR parameter
//! generator (Poseidon paper, `generate_parameters_grain.sage`) for
//! `GF(p), alpha=5, n=128, t=3, R_F=8, R_P=57`; the MDS matrix is the Cauchy
//! matrix `M[i][j] = 1 / (i + 3 + j)`. The same generator reproduces the
//! BN254 constants used by the Groth16/PLONK circuits.

use winterfell::math::{fields::f128::BaseElement, FieldElement};

pub const WIDTH: usize = 3;
pub const FULL_ROUNDS: usize = 8;
pub const PARTIAL_ROUNDS: usize = 57;
pub const TOTAL_ROUNDS: usize = FULL_ROUNDS + PARTIAL_ROUNDS;

/// Number of trace rows reserved for one hash: 65 round states plus the final
/// state, padded to a power of two so several hashes can share one trace.
pub const ROUNDS_PER_HASH: usize = 128;

const FIELD_SIZE: usize = 128;
const MODULUS: u128 = u128::MAX - 45 * (1u128 << 40) + 2;

pub fn is_full_round(round: usize) -> bool {
    round < FULL_ROUNDS / 2 || round >= FULL_ROUNDS / 2 + PARTIAL_ROUNDS
}

pub fn sbox(value: BaseElement) -> BaseElement {
    let squared = value * value;
    squared * squared * value
}

pub fn mds() -> [[BaseElement; WIDTH]; WIDTH] {
    let mut matrix = [[BaseElement::ZERO; WIDTH]; WIDTH];
    for (row, entries) in matrix.iter_mut().enumerate() {
        for (column, entry) in entries.iter_mut().enumerate() {
            *entry = BaseElement::new((row + WIDTH + column) as u128).inv();
        }
    }
    matrix
}

pub fn apply_round(
    mut state: [BaseElement; WIDTH],
    round_constants: &[BaseElement; WIDTH],
    full_round: bool,
    mds: &[[BaseElement; WIDTH]; WIDTH],
) -> [BaseElement; WIDTH] {
    for i in 0..WIDTH {
        state[i] += round_constants[i];
    }
    if full_round {
        for value in &mut state {
            *value = sbox(*value);
        }
    } else {
        state[0] = sbox(state[0]);
    }

    let mut mixed = [BaseElement::ZERO; WIDTH];
    for row in 0..WIDTH {
        for column in 0..WIDTH {
            mixed[row] += mds[row][column] * state[column];
        }
    }
    mixed
}

pub fn hash2(left: BaseElement, right: BaseElement) -> BaseElement {
    let constants = round_constants();
    let mds = mds();
    let mut state = [BaseElement::ZERO, left, right];
    for (round, round_constants) in constants.iter().enumerate() {
        state = apply_round(state, round_constants, is_full_round(round), &mds);
    }
    state[0]
}

/// Round constants generated by the reference Grain LFSR.
pub fn round_constants() -> [[BaseElement; WIDTH]; TOTAL_ROUNDS] {
    let mut grain = Grain::new();
    let mut constants = [[BaseElement::ZERO; WIDTH]; TOTAL_ROUNDS];
    for round in constants.iter_mut() {
        for constant in round.iter_mut() {
            loop {
                let value = grain.next_u128();
                if value < MODULUS {
                    *constant = BaseElement::new(value);
                    break;
                }
            }
        }
    }
    constants
}

/// The 80-bit Grain LFSR used by the Poseidon reference parameter generator.
struct Grain {
    bits: [bool; 80],
}

impl Grain {
    fn new() -> Self {
        let mut initial = Vec::with_capacity(80);
        // field = 1 (GF(p)), sbox = 0 (x^alpha), n = 128, t = 3, R_F = 8, R_P = 57.
        push_bits(&mut initial, 1, 2);
        push_bits(&mut initial, 0, 4);
        push_bits(&mut initial, FIELD_SIZE, 12);
        push_bits(&mut initial, WIDTH, 12);
        push_bits(&mut initial, FULL_ROUNDS, 10);
        push_bits(&mut initial, PARTIAL_ROUNDS, 10);
        initial.extend(core::iter::repeat(true).take(30));
        assert_eq!(initial.len(), 80);

        let mut bits = [false; 80];
        bits.copy_from_slice(&initial);
        let mut grain = Self { bits };
        for _ in 0..160 {
            grain.step();
        }
        grain
    }

    fn step(&mut self) -> bool {
        let new_bit = self.bits[62]
            ^ self.bits[51]
            ^ self.bits[38]
            ^ self.bits[23]
            ^ self.bits[13]
            ^ self.bits[0];
        self.bits.copy_within(1..80, 0);
        self.bits[79] = new_bit;
        new_bit
    }

    fn next_bit(&mut self) -> bool {
        let mut bit = self.step();
        while !bit {
            self.step();
            bit = self.step();
        }
        self.step()
    }

    fn next_u128(&mut self) -> u128 {
        let mut value = 0u128;
        for _ in 0..FIELD_SIZE {
            value = (value << 1) | (self.next_bit() as u128);
        }
        value
    }
}

fn push_bits(bits: &mut Vec<bool>, value: usize, width: usize) {
    for shift in (0..width).rev() {
        bits.push((value >> shift) & 1 == 1);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn grain_matches_reference_constants() {
        let constants = round_constants();
        assert_eq!(constants[0][0], BaseElement::new(0x9fb3847bb756de126ad98cb9249ba64c));
        assert_eq!(constants[0][1], BaseElement::new(0xcc72859e78635b6c35c68a51877c1b50));
        assert_eq!(constants[0][2], BaseElement::new(0x86cacb983d034f5fd54f673f5e5e441b));
        assert_eq!(
            constants[TOTAL_ROUNDS - 1][2],
            BaseElement::new(0x49c6fb3ef3c55de45fc19ba83577fadd)
        );
    }

    #[test]
    fn mds_is_the_cauchy_matrix() {
        let matrix = mds();
        assert_eq!(matrix[0][0], BaseElement::new(3).inv());
        assert_eq!(matrix[2][2], BaseElement::new(7).inv());
    }

    #[test]
    fn hash2_matches_reference_vector() {
        assert_eq!(
            hash2(BaseElement::new(1), BaseElement::new(2)),
            BaseElement::new(0x2c668cb247012a9c33e370191154de54)
        );
    }
}
